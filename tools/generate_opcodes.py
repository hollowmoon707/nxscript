"""Generate the NeoX opcode module from the four authoritative CSV tables."""

import argparse
import csv
from pathlib import Path

HAVE_ARGUMENT = 0x5A
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "src/nxscript/_opcode_data.py"


def rows(directory, name):
    with (directory / f"{name}.csv").open(encoding="utf-8-sig", newline="") as source:
        yield from csv.DictReader(source)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def number(row, column):
    value = int(row[f"{column}_hex"], 16)
    require(0 <= value <= 255 and value == int(row[f"{column}_dec"]), f"bad byte in {row}")
    return value


def generate(directory):
    index = {}
    for row in rows(directory, "opindex"):
        byte = number(row, "byte")
        require(byte not in index, f"duplicate indexed byte {byte:#04x}")
        index[byte] = row["role"], row["status"]
    require(set(index) == set(range(256)), "opindex must cover all 256 bytes")
    fillers = [byte for byte, entry in index.items() if entry == ("combo-filler", "resolved")]
    require(len(fillers) == 1 and fillers[0] >= HAVE_ARGUMENT, "expected one operand-width filler")
    filler = fillers[0]
    used = {filler}

    direct, stock_names = {}, {}
    for row in rows(directory, "opdirect"):
        encoded, stock = number(row, "perm"), number(row, "stock")
        name = row["name"]
        require(index[encoded] == ("direct", "resolved") and encoded not in used, f"bad direct row {row}")
        require(stock not in stock_names, f"duplicate stock opcode {stock:#04x}")
        require((encoded >= HAVE_ARGUMENT) == (stock >= HAVE_ARGUMENT) == (row["has_arg"] == "yes"),
                f"inconsistent direct width in {row}")
        direct[encoded] = stock
        stock_names[stock] = name
        used.add(encoded)
    require(len(set(stock_names.values())) == len(stock_names), "duplicate stock names")

    expansions = {}
    for table, column, role in [("opfused", "perm", "fused"), ("opprev", "prev", "combo-head")]:
        for row in rows(directory, table):
            encoded = number(row, column)
            require(index[encoded] == (role, "resolved") and encoded not in used, f"bad expansion row {row}")
            names = row["expands_to"].split(";")
            stocks = [int(text, 16) for text in row["stock_hex_list"].split(";")]
            operands = row["arg"].split(";")
            require(len(names) == len(stocks) == len(operands) and 2 <= len(stocks) <= 3,
                    f"bad expansion lengths in {row}")
            expansion = []
            slots = []
            for stock, name, spec in zip(stocks, names, operands):
                require(stock_names.get(stock) == name, f"unknown stock opcode in {row}")
                require((stock >= HAVE_ARGUMENT) == (spec != "-1"), f"bad operand width in {row}")
                if spec.startswith("c"):
                    operand = int(spec[1:])
                    require(0 <= operand <= 65535, f"bad constant operand in {row}")
                    source = ("constant", operand)
                elif spec == "-1":
                    source = ("none", 0)
                else:
                    slot = int(spec)
                    slots.append(slot)
                    source = ("slot", slot)
                expansion.append((stock, *source))
            count = len(slots)
            require(sorted(slots) == list(range(count)), f"bad operand slots in {row}")
            require((count > 1) == (role == "combo-head") and (count > 0) == (encoded >= HAVE_ARGUMENT),
                    f"inconsistent expansion width in {row}")
            expansions[encoded] = (count, tuple(expansion))
            used.add(encoded)

    require(used == {byte for byte, (_, status) in index.items() if status == "resolved"},
            "resolved opcodes in opindex do not match the decode tables")
    lines = [
        '"""Generated by tools/generate_opcodes.py from the NeoX opcode CSVs."""',
        "",
        f"COMBO_FILLER = 0x{filler:02x}",
        f"STOCK_EXTENDED_ARG = 0x{next(key for key, name in stock_names.items() if name == 'EXTENDED_ARG'):02x}",
        "",
        "DIRECT = {",
    ]
    lines.extend(f"    0x{encoded:02x}: 0x{stock:02x},  # {stock_names[stock]}"
                 for encoded, stock in sorted(direct.items()))
    lines.extend(["}", "", "EXPANSIONS = {"])
    lines.extend(f"    0x{key:02x}: {value!r}," for key, value in sorted(expansions.items()))
    lines.extend(["}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tables", type=Path, help="directory containing the four CSVs")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="check the output without writing")
    args = parser.parse_args()
    try:
        result = generate(args.tables).encode("utf-8")
        if args.check:
            require(args.out.read_bytes() == result, f"{args.out} needs regenerating")
        else:
            args.out.write_bytes(result)
    except (OSError, ValueError, KeyError) as exc:
        parser.exit(1, f"{exc}\n")


if __name__ == "__main__":
    main()
